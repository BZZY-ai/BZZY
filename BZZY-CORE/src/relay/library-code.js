import { createHmac, randomBytes } from 'node:crypto';
import { canonical } from '../engine/database.js';
import { fail } from '../validation.js';

const field = value => typeof value === 'string' && /^[A-Za-z0-9_-]{43}$/.test(value) &&
  Buffer.from(value, 'base64url').length === 32 && Buffer.from(value, 'base64url').toString('base64url') === value;
export function libraryApproval(value) {
  if (value === undefined || value === 'manual') return 'manual';
  if (value !== 'code') fail('INVALID_REQUEST', 'Choose a valid Library code approval mode.');
  return value;
}
export function createLibraryCode({ code, fingerprint, sha256 }) {
  const token = code?.startsWith('BZZY-LIBRARY-') ? code.slice(13) : null;
  if (!field(token) || !field(fingerprint) || !/^[a-f0-9]{64}$/.test(sha256 || '')) fail('INVALID_REQUEST', 'Invalid Library code source.');
  const secret = randomBytes(32).toString('base64url');
  return { secret, code: ['BZZY-LIBRARY-2', token, fingerprint, secret, Buffer.from(sha256, 'hex').toString('base64url')].join('.') };
}
// This secret is generated by Core and never sent in Relay invitation metadata.
// The pasted capability pins both the signed sender and exact immutable archive.
export function decodeLibraryCode(value) {
  if (typeof value !== 'string' || !value.startsWith('BZZY-LIBRARY-2.')) return null;
  const parts = value.split('.');
  if (parts.length !== 5 || !parts.slice(1).every(field)) fail('INVALID_REQUEST', 'Use a complete Library export code.');
  return { code: 'BZZY-LIBRARY-' + parts[1], fingerprint: parts[2], secret: parts[3], sha256: Buffer.from(parts[4], 'base64url').toString('hex') };
}
export function libraryCodeProof(secret, { shareId, grantId, recipientId, sha256 }) {
  if (!field(secret)) fail('INVALID_REQUEST', 'Invalid Library code proof.');
  return createHmac('sha256', Buffer.from(secret, 'base64url')).update(canonical(['bzzy-library-code', 2, shareId, grantId, recipientId, sha256])).digest('base64url');
}
